from ai_engine import ask_gigachat


def analyze_task(
    problem,
    object_name,
    useful_action,
    undesired_effect,
    goal,
    constraints,
    resources
):
    prompt = f"""
Ты — эксперт по ТРИЗ (теории решения изобретательских задач).
Твоя задача — провести подробный и практический анализ проблемы.

Данные пользователя:

Проблема: {problem}
Объект: {object_name}
Полезная функция: {useful_action or "Не указана"}
Нежелательный эффект: {undesired_effect or "Не указан"}
Желаемый результат: {goal or "Не указан"}
Ограничения: {constraints or "Не указаны"}
Доступные ресурсы: {resources or "Не указаны"}

Проведи анализ по следующей структуре:

1. ИСХОДНАЯ ПРОБЛЕМА
Переформулируй проблему кратко и точно.

2. ТЕХНИЧЕСКОЕ ПРОТИВОРЕЧИЕ
Определи, какое улучшение приводит к нежелательному эффекту.
Если данных недостаточно, предложи вероятную формулировку и обозначь предположение.

3. ФИЗИЧЕСКОЕ ПРОТИВОРЕЧИЕ
Определи, какие противоположные требования предъявляются к объекту.
Если оно не выявляется, объясни почему.

4. ИДЕАЛЬНЫЙ КОНЕЧНЫЙ РЕЗУЛЬТАТ (ИКР)
Сформулируй конкретный желаемый результат.

5. АНАЛИЗ РЕСУРСОВ
Найди доступные ресурсы объекта, среды, пространства, времени и материалов.
Не выдумывай ресурсы, которых нет в условии.

6. ПРИМЕНЕНИЕ ПРИЁМОВ ТРИЗ
Выбери наиболее подходящие принципы из 40 изобретательских принципов.
Объясни, почему каждый из них подходит.

7. ВАРИАНТЫ РЕШЕНИЯ
Предложи минимум 3 конкретных варианта.
Для каждого укажи:
- Суть решения.
- Как оно работает.
- Какое противоречие устраняет.
- Преимущества и возможные недостатки.

8. ЛУЧШЕЕ РЕШЕНИЕ
Выбери наиболее перспективный вариант и обоснуй выбор.

Пиши на русском языке, понятно и подробно.
Не ограничивайся общими советами.
Не выдавай предположения за факты.
Используй реальные методы ТРИЗ.
"""

    answer = ask_gigachat(prompt)

    return {
        "problem_analysis": answer,
        "contradiction": "Подробный анализ приведён ниже.",
        "ideal_result": "Подробный анализ приведён ниже.",
        "resources": resources or "Не указаны.",
        "constraints": constraints or "Не указаны."
    }
